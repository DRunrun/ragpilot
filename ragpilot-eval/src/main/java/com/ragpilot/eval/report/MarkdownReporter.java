package com.ragpilot.eval.report;

import com.ragpilot.eval.runner.EvalRunner;

import java.time.LocalDate;
import java.time.ZoneId;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;

/**
 * 消融报告生成器：把多份 {@link EvalRunner.EvalReport} 拼成可贴 README 的 Markdown 表。
 *
 * <p>链路位置：评测体系出口（F2.9）。表头固定为 evaluation.md 约定：
 * {@code setup | Recall@5 | Faithfulness | AnswerRelevancy | notes}，并附变化百分比。
 */
public final class MarkdownReporter {

    /**
     * 一行消融 setup 的展示名与报告。
     *
     * @param setup  如 {@code VECTOR} / {@code HYBRID} / {@code HYBRID_RERANK}
     * @param report 对应模式的评测报告
     * @param notes  备注（可空）
     */
    public record SetupRow(String setup, EvalRunner.EvalReport report, String notes) {
        public SetupRow {
            Objects.requireNonNull(setup, "setup");
            Objects.requireNonNull(report, "report");
            notes = notes == null ? "" : notes;
        }
    }

    /**
     * 生成完整 Markdown 报告正文。
     *
     * @param rows 至少 2 行（消融对比）；第一行作为百分比变化的基线
     * @return Markdown 文本
     */
    public String render(List<SetupRow> rows) {
        Objects.requireNonNull(rows, "rows");
        if (rows.size() < 2) {
            throw new IllegalArgumentException("ablation report needs >= 2 setups, got " + rows.size());
        }

        String date = LocalDate.now(ZoneId.systemDefault()).toString();
        StringBuilder md = new StringBuilder();
        md.append("# RagPilot Ablation Report (").append(date).append(")\n\n");
        md.append("> Auto-generated by MarkdownReporter. Re-run: ")
                .append("`java -jar ragpilot-bootstrap.jar eval --mode=<MODE>`\n\n");

        md.append("## Metrics\n\n");
        md.append("| setup | Recall@5 | Faithfulness | AnswerRelevancy | notes |\n");
        md.append("|---|---:|---:|---:|---|\n");

        SetupRow baseline = rows.get(0);
        for (SetupRow row : rows) {
            EvalRunner.EvalReport r = row.report();
            md.append("| ").append(row.setup()).append(" | ")
                    .append(fmt(r.recallAtK())).append(" | ")
                    .append(fmt(r.faithfulness())).append(" | ")
                    .append(fmt(r.answerRelevancy())).append(" | ")
                    .append(escapeCell(row.notes())).append(" |\n");
        }

        md.append("\n## Delta vs baseline (").append(baseline.setup()).append(")\n\n");
        md.append("| setup | Recall@5 Δ% | Faithfulness Δ% | AnswerRelevancy Δ% |\n");
        md.append("|---|---:|---:|---:|\n");
        for (int i = 1; i < rows.size(); i++) {
            SetupRow row = rows.get(i);
            md.append("| ").append(row.setup()).append(" | ")
                    .append(pctDelta(baseline.report().recallAtK(), row.report().recallAtK())).append(" | ")
                    .append(pctDelta(baseline.report().faithfulness(), row.report().faithfulness())).append(" | ")
                    .append(pctDelta(baseline.report().answerRelevancy(), row.report().answerRelevancy()))
                    .append(" |\n");
        }

        md.append("\n## Extra\n\n");
        md.append("| setup | MRR | RefusalAccuracy | questions |\n");
        md.append("|---|---:|---:|---:|\n");
        for (SetupRow row : rows) {
            EvalRunner.EvalReport r = row.report();
            md.append("| ").append(row.setup()).append(" | ")
                    .append(fmt(r.mrr())).append(" | ")
                    .append(fmt(r.refusalAccuracy())).append(" | ")
                    .append(r.questionCount()).append(" |\n");
        }

        md.append("\n## Conclusion\n\n");
        md.append(buildConclusion(rows)).append('\n');
        return md.toString();
    }

    /**
     * 默认输出文件名：{@code reports/ablation-YYYYMMDD.md}。
     */
    public static String defaultFileName() {
        return "reports/ablation-" + LocalDate.now(ZoneId.systemDefault()) + ".md";
    }

    private static String buildConclusion(List<SetupRow> rows) {
        // 找 Recall 最高的非基线 setup，写一句人话结论
        SetupRow baseline = rows.get(0);
        SetupRow best = baseline;
        for (SetupRow row : rows) {
            double a = nullToNeg(row.report().recallAtK());
            double b = nullToNeg(best.report().recallAtK());
            if (a > b) {
                best = row;
            }
        }
        if (best == baseline) {
            return "Under current corpus, baseline **" + baseline.setup()
                    + "** already leads on Recall@5; re-check hybrid/rerank wiring or enlarge evidence docs.";
        }
        String delta = pctDelta(baseline.report().recallAtK(), best.report().recallAtK());
        return "**" + best.setup() + "** improves Recall@5 by " + delta
                + " over **" + baseline.setup() + "** on golden v1.0.";
    }

    private static double nullToNeg(Double v) {
        return v == null || v.isNaN() ? -1.0 : v;
    }

    static String fmt(Double v) {
        if (v == null || v.isNaN()) {
            return "n/a";
        }
        return String.format(Locale.ROOT, "%.3f", v);
    }

    /**
     * 相对基线的变化百分比：{@code (cur - base) / base * 100}；基线为 0/空时返回 n/a。
     */
    static String pctDelta(Double baseline, Double current) {
        if (baseline == null || current == null || baseline.isNaN() || current.isNaN()) {
            return "n/a";
        }
        if (Math.abs(baseline) < 1e-12) {
            return current > 0 ? "+inf" : "0.0%";
        }
        double pct = (current - baseline) / baseline * 100.0;
        return String.format(Locale.ROOT, "%+.1f%%", pct);
    }

    private static String escapeCell(String s) {
        return s.replace("|", "\\|").replace("\n", " ");
    }

    /**
     * 按 setup 名聚合多份报告（后者覆盖同名），保持插入序。
     */
    public static List<SetupRow> fromReports(Map<String, EvalRunner.EvalReport> bySetup, Map<String, String> notes) {
        Map<String, String> n = notes == null ? Map.of() : notes;
        List<SetupRow> rows = new ArrayList<>();
        for (Map.Entry<String, EvalRunner.EvalReport> e : bySetup.entrySet()) {
            rows.add(new SetupRow(e.getKey(), e.getValue(), n.getOrDefault(e.getKey(), "")));
        }
        return rows;
    }

    /** 便于按 VECTOR → HYBRID → HYBRID_RERANK 排序插入。 */
    public static Map<String, EvalRunner.EvalReport> orderedMap() {
        return new LinkedHashMap<>();
    }
}
